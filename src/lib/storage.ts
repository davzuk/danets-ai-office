// File storage for the media library.
//
//   STORAGE_DRIVER=local (default in dev): files under STORAGE_LOCAL_DIR,
//     served by /api/media/files/<key>. Single-instance only.
//   STORAGE_DRIVER=s3: any S3-compatible store (AWS S3, Cloudflare R2,
//     DigitalOcean Spaces, MinIO). Requests are signed with SigV4 here, so
//     no SDK dependency. Objects must be publicly readable at
//     S3_PUBLIC_URL (Instagram and LinkedIn fetch media by URL).

import { createHash, createHmac } from "crypto";
import { mkdir, readFile, rm, writeFile } from "fs/promises";
import path from "path";

export interface StorageDriver {
  readonly name: "local" | "s3";
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  delete(key: string): Promise<void>;
  publicUrl(key: string): string;
}

type Env = Record<string, string | undefined>;

/** Keys are generated by us: "<businessId>/<yyyy>/<mm>/<id>.<ext>". Reject anything else. */
export function isSafeKey(key: string): boolean {
  return /^[A-Za-z0-9_-]+(\/[A-Za-z0-9_-]+)*\.[a-z0-9]{2,5}$/.test(key) && !key.includes("..") && key.length <= 191;
}

function appUrl(env: Env) {
  return (env.NEXT_PUBLIC_APP_URL || "http://localhost:3000").replace(/\/+$/, "");
}

// ─── Local disk ────────────────────────────────────────────────────────

export function localRoot(env: Env = process.env) {
  return path.resolve(env.STORAGE_LOCAL_DIR || path.join(process.cwd(), "storage", "media"));
}

/** Absolute path for a key, guaranteed to stay inside the storage root. */
export function localPath(key: string, env: Env = process.env): string {
  if (!isSafeKey(key)) throw new Error("Invalid storage key");
  const root = localRoot(env);
  const full = path.resolve(root, key);
  if (!full.startsWith(root + path.sep)) throw new Error("Invalid storage key");
  return full;
}

export function localDriver(env: Env = process.env): StorageDriver {
  return {
    name: "local",
    async put(key, body) {
      const file = localPath(key, env);
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, body);
    },
    async delete(key) {
      await rm(localPath(key, env), { force: true });
    },
    publicUrl: (key) => `${appUrl(env)}/api/media/files/${key}`,
  };
}

export async function readLocalFile(key: string, env: Env = process.env): Promise<Buffer | null> {
  try {
    return await readFile(localPath(key, env));
  } catch {
    return null;
  }
}

// ─── S3-compatible (SigV4) ─────────────────────────────────────────────

const sha256Hex = (data: string | Buffer) => createHash("sha256").update(data).digest("hex");
const hmac = (key: Buffer | string, data: string) => createHmac("sha256", key).update(data).digest();

/** RFC 3986 encoding as SigV4 wants it; "/" kept for object keys. */
export function uriEncode(s: string, keepSlash = true) {
  return encodeURIComponent(s)
    .replace(/[!'()*]/g, (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`)
    .replace(/%2F/g, keepSlash ? "/" : "%2F");
}

export interface SignInput {
  method: string;
  url: URL;
  headers: Record<string, string>;
  payloadHash: string;
  accessKeyId: string;
  secretAccessKey: string;
  region: string;
  service?: string;
  now?: Date;
}

/** AWS Signature Version 4. Returns the headers to send (incl. Authorization). */
export function signV4(input: SignInput): Record<string, string> {
  const service = input.service ?? "s3";
  const now = input.now ?? new Date();
  const amzDate = now.toISOString().replace(/[:-]|\.\d{3}/g, "");
  const day = amzDate.slice(0, 8);

  const headers: Record<string, string> = {
    ...input.headers,
    host: input.url.host,
    "x-amz-date": amzDate,
    "x-amz-content-sha256": input.payloadHash,
  };
  const lower = Object.fromEntries(Object.entries(headers).map(([k, v]) => [k.toLowerCase(), String(v).trim().replace(/\s+/g, " ")]));
  const signedHeaders = Object.keys(lower).sort();
  const canonicalHeaders = signedHeaders.map((k) => `${k}:${lower[k]}\n`).join("");
  const query = [...input.url.searchParams.entries()]
    .map(([k, v]) => [uriEncode(k, false), uriEncode(v, false)])
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([k, v]) => `${k}=${v}`)
    .join("&");

  const canonicalRequest = [
    input.method,
    uriEncode(decodeURIComponent(input.url.pathname)),
    query,
    canonicalHeaders,
    signedHeaders.join(";"),
    input.payloadHash,
  ].join("\n");
  const scope = `${day}/${input.region}/${service}/aws4_request`;
  const stringToSign = ["AWS4-HMAC-SHA256", amzDate, scope, sha256Hex(canonicalRequest)].join("\n");
  const kSigning = hmac(hmac(hmac(hmac(`AWS4${input.secretAccessKey}`, day), input.region), service), "aws4_request");
  const signature = createHmac("sha256", kSigning).update(stringToSign).digest("hex");

  return {
    ...headers,
    authorization: `AWS4-HMAC-SHA256 Credential=${input.accessKeyId}/${scope}, SignedHeaders=${signedHeaders.join(";")}, Signature=${signature}`,
  };
}

export function s3Driver(env: Env = process.env): StorageDriver {
  const endpoint = env.S3_ENDPOINT?.replace(/\/+$/, "");
  const bucket = env.S3_BUCKET;
  const accessKeyId = env.S3_ACCESS_KEY_ID;
  const secretAccessKey = env.S3_SECRET_ACCESS_KEY;
  const publicBase = env.S3_PUBLIC_URL?.replace(/\/+$/, "");
  const region = env.S3_REGION || "auto"; // R2 uses "auto"; AWS needs the bucket's region
  if (!endpoint || !bucket || !accessKeyId || !secretAccessKey || !publicBase) {
    throw new Error("STORAGE_DRIVER=s3 needs S3_ENDPOINT, S3_BUCKET, S3_ACCESS_KEY_ID, S3_SECRET_ACCESS_KEY and S3_PUBLIC_URL");
  }
  // Path-style addressing works on every S3-compatible service.
  const objectUrl = (key: string) => new URL(`${endpoint}/${uriEncode(bucket)}/${uriEncode(key)}`);

  async function send(method: "PUT" | "DELETE", key: string, body?: Buffer, contentType?: string) {
    const url = objectUrl(key);
    const payloadHash = sha256Hex(body ?? "");
    const headers = signV4({
      method,
      url,
      headers: body
        ? { "content-type": contentType ?? "application/octet-stream", "content-length": String(body.length), "cache-control": "public, max-age=31536000, immutable" }
        : {},
      payloadHash,
      accessKeyId: accessKeyId!,
      secretAccessKey: secretAccessKey!,
      region,
    });
    delete headers.host; // fetch sets it
    const res = await fetch(url, {
      method,
      headers,
      body: body ? new Uint8Array(body) : undefined,
      signal: AbortSignal.timeout(120_000),
    });
    if (!res.ok && !(method === "DELETE" && res.status === 404)) {
      const text = (await res.text().catch(() => "")).slice(0, 300);
      throw new Error(`Storage ${method} failed (${res.status}): ${text}`);
    }
  }

  return {
    name: "s3",
    put: (key, body, contentType) => send("PUT", key, body, contentType),
    delete: (key) => send("DELETE", key),
    publicUrl: (key) => `${publicBase}/${uriEncode(key)}`,
  };
}

let cached: StorageDriver | null = null;

export function getStorage(env: Env = process.env): StorageDriver {
  if (cached && env === process.env) return cached;
  const driver = (env.STORAGE_DRIVER || "local").toLowerCase() === "s3" ? s3Driver(env) : localDriver(env);
  if (env === process.env) cached = driver;
  return driver;
}

/** Test hook. */
export function resetStorageForTests() {
  cached = null;
}
